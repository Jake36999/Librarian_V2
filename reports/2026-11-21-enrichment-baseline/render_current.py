"""Render the current source-stage child without executing library operations."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

from resource_librarian.canvas import service

HERE = Path(__file__).resolve().parent
STEM = "source-enrichment-current"


def module_at(name, path):
    definition = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(definition)
    definition.loader.exec_module(module)
    return module


def build(stem=STEM, *, reflow_generated=False, reroute_generated=False):
    layout = module_at("current_enrichment_layout", HERE / "build_artifacts.py")
    render = layout.renderer()
    source = HERE / f"{stem}.spec.yaml"
    spec = render.load(source)
    spec["_file"] = source.name
    library = {model["diagram"]: model for path in HERE.glob("*.spec.yaml")
               for model in [render.load(path)]}
    problems, scenarios = layout.checks(spec, render, library)
    if problems:
        raise ValueError(problems)
    tree, tests = render.tree_and_tests(spec, scenarios)
    views = "\n".join([
        "<!-- generated by render_current.py using the supplied renderer; edit the spec -->",
        f"# {spec['title']}", "",
        f"**Status:** descriptive current-code contract. The [use-case description]({stem}.md) explains ownership, evidence and limitations; proposed autonomous coordination is not claimed here.", "",
        "Prototype scenarios are guarded departures and rejoins, not every combination of repeated items or evidence of fresh execution.", "",
        "## Validation", "", "No structural or cross-view/reference flags.", "",
        "## Activity diagram", "", "```mermaid", render.mermaid(spec), "```", "",
        "## Written use case", "", render.written_use_case(spec, scenarios), "",
        "## Lane load", "", render.lane_load(spec, scenarios), "",
        f"## Decision tree with {len(scenarios)} extension scenarios", "", tree, "",
        "## Scenario test table", "", tests, "",
        "These are generated consistency cases, not newly executed runtime tests.", "",
    ])
    generated = layout.managed_canvas(spec, render)
    target = HERE / f"{stem}.canvas"
    preview = layout.actor_preview(target, generated, spec, reflow_generated=reflow_generated,
                                   reroute_generated=reroute_generated,
                                   validation_path=HERE / f"{stem}.validation.json")
    result = service.commit(target, preview)
    (HERE / f"{stem}.views.md").write_text(views, encoding="utf-8")
    saved = json.loads(target.read_text(encoding="utf-8"))
    raster = module_at("current_enrichment_raster", HERE / "render_preview.py")
    bottom = max(node["y"] + node["height"] for node in saved["nodes"])
    right = max(node["x"] + node["width"] for node in saved["nodes"])
    overview_clipped = raster.render(saved, HERE / f"{stem}.png", (0, -220, right + 30, bottom + 30), .36,
                                    spec['title'])
    nodes = {node["id"].removeprefix(service.MANAGED_PREFIX): node for node in saved["nodes"]}
    first, last = ("parse", "data") if stem == STEM else ("foldercontrols", "account")
    clipped = raster.render(saved, HERE / f"{stem}-detail.png",
                            (0, nodes[first]["y"] - 50, right + 30, nodes[last]["y"] + 220),
                            .8, spec['title'])
    receipt = {
        "status": "descriptive diagram checks; not a new runtime execution",
        "model": stem,
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "canvas_revision": result["revision"],
        "canvas_nodes": len(saved["nodes"]), "edges": len(saved["edges"]),
        "numbered_steps": len([n for n in spec["nodes"] if n.get("step")]),
        "extension_scenarios": len(scenarios), "structural_reference_flags": [],
        "card_overlaps": layout.overlaps(saved), "detail_text_overflow": clipped,
        "edge_card_intersections": layout.routing().intersections(saved),
        "overview_clipped_at_reduced_scale": overview_clipped,
        "generated_relayout": preview["changes"]["generated_relayout"],
        "call_outcomes": sorted({render.outcome(n) for n in spec["nodes"] if n["kind"] == "end"}),
        "write": "existing canvas service preview and revision/hash-checked commit; profile=None",
    }
    receipt_path = HERE / f"{stem}.validation.json"
    if receipt_path.exists():
        previous = receipt_path.read_bytes()
        history = HERE / "correction-history"
        history.mkdir(exist_ok=True)
        archived = history / f"{stem}.{hashlib.sha256(previous).hexdigest()[:16]}.json"
        if not archived.exists():
            archived.write_bytes(previous)
        receipt["previous_validation"] = str(archived.relative_to(HERE))
    receipt_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k:v for k,v in receipt.items() if k not in {"generated_relayout", "overview_clipped_at_reduced_scale"}}, indent=2))
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reflow-generated", action="store_true")
    parser.add_argument("--reroute-generated", action="store_true")
    parser.add_argument("--stem", choices=[STEM, "batch-enrichment-current"], action="append")
    options = parser.parse_args()
    for stem in options.stem or [STEM, "batch-enrichment-current"]:
        build(stem, reflow_generated=options.reflow_generated,
              reroute_generated=options.reroute_generated)
