"""Render the proposed enrichment use case without changing product code or accepted canvases."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from collections import Counter
from pathlib import Path

from resource_librarian.canvas import service

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
EXAMPLES = REPO / "reports/2026-11-20-workflow-map/examples/ingestion"
BASELINE = REPO / "reports/2026-11-21-enrichment-baseline"
STEM = "proposed-tobe-enrichment"


def module_at(name: str, location: Path):
    spec = importlib.util.spec_from_file_location(name, location)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def actor_preview(target, generated, model, layout, *, reflow_generated=False):
    """Use the shared report authoring path and its saved-revision/Owner-edit guard."""
    return layout.actor_preview(target, generated, model,
                                reflow_generated=reflow_generated)


def build(*, reflow_generated=False):
    render = module_at("accepted_spec_renderer", EXAMPLES / "render_spec.py")
    layout = module_at("review_canvas_layout", BASELINE / "build_artifacts.py")
    model_path = HERE / f"{STEM}.spec.yaml"
    model = render.load(model_path)
    model["_file"] = model_path.name
    # Reuse UC-D's existing three-outcome call interface, not its prototype execution body.
    doctor = render.load(EXAMPLES / "doctor.spec.yaml")
    library = {"UC-D": doctor, model["diagram"]: model}
    problems = render.validate(model)
    for field, values in (("node", [node["id"] for node in model["nodes"]]),
                          ("extension", [edge["ext"] for edge in model["edges"] if edge.get("ext")])):
        problems += [f"duplicate {field}: {value}" for value, count in Counter(values).items() if count != 1]
    main = render.main_path(model)
    steps = [node["step"] for node in model["nodes"] if node.get("step")]
    if sorted(steps) != list(range(1, len(steps) + 1)):
        problems.append("main steps must be consecutive and unique")
    problems += [f"numbered step outside main path: {node['id']}"
                 for node in model["nodes"] if node.get("step") and node["id"] not in main]
    if problems:
        raise ValueError(problems)
    scenarios = render.paths(model)
    flags = render.cross_check(model, scenarios) + render.check_references(model, library)
    if flags:
        raise ValueError(flags)
    tree, tests = render.tree_and_tests(model, scenarios)
    actors = [lane for lane in model["lanes"] if lane != "Core"]
    use_case = ['flowchart LR', '  subgraph system["Librarian"]',
                '    goal(["Enrich authorized captured sources"])', '  end']
    for index, actor in enumerate(actors):
        use_case.append(f'  actor{index}(["{actor}"]) --- goal')
    views = "\n".join([
        "<!-- generated by render_proposal.py using the supplied render_spec.py; edit the spec -->",
        "# Proposed to-be enrichment views", "",
        "**Status:** proposed behavior for review. The [proposal](PROPOSAL.md) supplies the nine-field use case, current-versus-proposed comparison, source evidence and implementation boundaries.", "",
        "These scenarios use the supplied prototype's extension-and-rejoin logic. They are not all combinations of repeated sources and faults, or evidence that the proposed pipeline has executed.", "",
        "## Validation", "", "No structural problems or cross-view/reference flags.", "",
        "## Use case diagram", "", "```mermaid", "\n".join(use_case), "```", "",
        "## Activity diagram", "", "```mermaid", render.mermaid(model), "```", "",
        "## Written use case", "", "The [use-case description](PROPOSAL.md#use-case-description) defines the goal, actors, preconditions, guarantee and assumptions.", "",
        render.written_use_case(model, scenarios), "",
        "## Lane load", "", render.lane_load(model, scenarios), "",
        f"## Decision tree with {len(scenarios)} extension scenarios", "", tree, "",
        "## Scenario test table", "", tests, "",
        "## Cross view check", "", "No flags.", "",
        "The two Doctor references handle exactly the existing UC-D outcomes: resolved, declined and escalated. Their execution is governed by current role/composition policy; the old prototype's automatic-rollback wording is not adopted.", "",
    ])
    generated = layout.managed_canvas(model, render)
    target = HERE / f"{STEM}.canvas"
    preview = actor_preview(target, generated, model, layout, reflow_generated=reflow_generated)
    collisions = layout.overlaps(preview["proposal"])
    if collisions:
        raise ValueError(f"inspect overlapping cards before writing: {collisions}")
    committed = service.commit(target, preview)
    (HERE / f"{STEM}.views.md").write_text(views, encoding="utf-8")
    canvas = json.loads(target.read_text(encoding="utf-8"))
    assert not layout.overlaps(canvas)
    assert all(edge.get("fromSide") and edge.get("toSide") for edge in canvas["edges"]
               if edge["id"].startswith(service.MANAGED_PREFIX))
    receipt = {
        "status": "proposal artifact validation, not runtime execution or Owner acceptance",
        "model_sha256": hashlib.sha256(model_path.read_bytes()).hexdigest(),
        "supplied_renderer_sha256": hashlib.sha256((EXAMPLES / "render_spec.py").read_bytes()).hexdigest(),
        "behavior_nodes": len(model["nodes"]),
        "canvas_nodes": len(canvas["nodes"]),
        "edges": len(canvas["edges"]),
        "main_steps": len(steps),
        "extension_scenarios": len(scenarios),
        "main_tier0_turns_by_prototype": render.tier0_turns(model, scenarios[0]),
        "structural_problems": problems,
        "cross_view_reference_flags": flags,
        "card_overlaps": [],
        "actor_reassignments": preview["changes"]["actor_reassignments"],
        "generated_relayout": preview["changes"]["generated_relayout"],
        "ownership_rule": "agents own interpretation, proposals and semantic judgement; Core performs declared scripts and mechanical checks/storage/dispatch",
        "canvas_revision": committed["revision"],
        "write": "existing canvas service preview then revision/hash-checked commit; profile=None",
        "doctor_reference_contract": ["declined", "escalated", "resolved"],
    }
    # Existing report helper renders reading aids from the saved positions; no canvas edits.
    raster = module_at("review_canvas_preview", BASELINE / "render_preview.py")
    bottom = max(node["y"] + node["height"] for node in canvas["nodes"])
    right = max(node["x"] + node["width"] for node in canvas["nodes"])
    receipt["overview_text_overflow"] = raster.render(
        canvas, HERE / "overview.png", (0, -220, right + 30, bottom + 30), .28,
        "Proposed to-be enrichment")
    cards = {node["id"].removeprefix(service.MANAGED_PREFIX): node for node in canvas["nodes"]}
    clipped = raster.render(canvas, HERE / "reading-and-derivations.png",
                            (0, cards["a7"]["y"] - 50, right + 30, cards["a12"]["y"] + 220), .8,
                            "Proposed reading and derivation ownership")
    receipt["reading_detail_text_overflow"] = clipped
    receipt["edge_card_intersections"] = layout.routing().intersections(canvas)
    receipt["preview"] = "deterministic raster reading aids, not an Obsidian application screenshot"
    receipt_path = HERE / "validation.json"
    if receipt_path.exists():
        previous = receipt_path.read_bytes()
        history = HERE / "correction-history"
        history.mkdir(exist_ok=True)
        archive = history / f"validation.{hashlib.sha256(previous).hexdigest()[:16]}.json"
        if not archive.exists():
            archive.write_bytes(previous)
        receipt["previous_validation"] = archive.relative_to(HERE).as_posix()
    receipt_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(receipt, indent=2))
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reflow-generated", action="store_true",
                        help="reflow only when the saved canvas matches its previous validation receipt")
    build(reflow_generated=parser.parse_args().reflow_generated)
