"""Render the three proposed report models through the existing guarded canvas service."""
from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BASE = ROOT / "reports/2026-11-21-enrichment-baseline"
ING = ROOT / "reports/2026-11-20-workflow-map/examples/ingestion"
STEMS = ("proposed-ingestion", "proposed-batch-enrichment", "proposed-source-enrichment")


def module(name, path):
    definition = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(definition)
    definition.loader.exec_module(result)
    return result


def prepared(stem, layout, render, library):
    source = HERE / f"{stem}.spec.yaml"
    spec = library[stem]
    spec["_file"] = source.name
    problems, scenarios = layout.checks(spec, render, library)
    if problems:
        raise ValueError((stem, problems))
    proof = json.loads((HERE / f"{stem}.presentation-proof.json").read_text(encoding="utf-8"))
    if hashlib.sha256(source.read_bytes()).hexdigest() != proof["normalized_spec_sha256"]:
        raise ValueError(f"{stem}: specification changed; review the presentation proof and geometry")
    original = render.load(HERE / proof["original_spec"])
    layout.routing().validate_terminal_fold(original, spec, proof["node_origins"])
    generated = layout.managed_canvas(spec, render)
    nodes = {node["id"].removeprefix("librarian-"): node for node in generated["nodes"]}
    for name, position in proof.get("node_y_overrides", {}).items():
        nodes[name]["y"] = position
    layout.routing().clear_layout(generated, minimum_pitch=proof["minimum_actor_pitch"])
    if layout.overlaps(generated):
        raise ValueError((stem, "overlapping cards"))
    target = HERE / f"{stem}.canvas"
    preview = layout.actor_preview(target, generated, spec,
                                   validation_path=HERE / f"{stem}.validation.json")
    if layout.routing().intersections(preview["proposal"]):
        raise ValueError((stem, "saved or proposed geometry contains an edge/card intersection"))
    tree, tests = render.tree_and_tests(spec, scenarios)
    actors = [lane for lane in spec["lanes"] if lane != "Core"]
    use_case = ["flowchart LR", '  subgraph librarian["Librarian"]',
                f'    goal(["{spec["title"]}"])', "  end"]
    for index, actor in enumerate(actors):
        use_case.append(f'  actor{index}(["{actor}"]) --- goal')
    views = "\n".join([
        "<!-- generated by build_family.py through the supplied render_spec.py; edit the spec -->",
        f"# {spec['title']}", "",
        f"**Status:** proposed behavioral integration. [Use-case description]({stem}.md) · [Family](README.md).", "",
        "Local report/end copies express the same guarded exit at different departures; they are not extra runtime actions. The presentation proof folds them back to the original model. Scenarios describe guarded departures/rejoins, not all repeated execution combinations.", "",
        "## Validation", "", "No structural, reference, card-overlap or preview edge/card intersection flags.", "",
        "## Use-case diagram", "", "```mermaid", "\n".join(use_case), "```", "",
        "## Activity diagram", "", "```mermaid", render.mermaid(spec), "```", "",
        "## Written use case", "", render.written_use_case(spec, scenarios), "",
        "## Lane load", "", render.lane_load(spec, scenarios), "",
        f"## Decision tree with {len(scenarios)} extension scenarios", "", tree, "",
        "## Scenario test table", "", tests, "",
        "These are artifact consistency cases, not executed runtime tests.", "",
    ])
    return source, target, spec, preview, views, scenarios, proof


def main():
    layout = module("family_layout", BASE / "build_artifacts.py")
    render = layout.renderer()
    library = {stem: render.load(HERE / f"{stem}.spec.yaml") for stem in STEMS}
    library["UC-D"] = render.load(ING / "doctor.spec.yaml")
    # Finish validation and previews for the entire family before committing any member.
    all_prepared = [prepared(stem, layout, render, library) for stem in STEMS]
    from resource_librarian.canvas import service
    raster = module("family_preview", BASE / "render_preview.py")
    receipts = []
    for source, target, spec, preview, views, scenarios, proof in all_prepared:
        stem = spec["diagram"]
        result = service.commit(target, preview)
        (HERE / f"{stem}.views.md").write_text(views, encoding="utf-8")
        saved = json.loads(target.read_text(encoding="utf-8"))
        right = max(n["x"] + n["width"] for n in saved["nodes"])
        bottom = max(n["y"] + n["height"] for n in saved["nodes"])
        clipped = raster.render(saved, HERE / f"{stem}.png", (0, -220, right + 30, bottom + 30),
                                .3, spec["title"])
        nodes = {n["id"].removeprefix("librarian-"): n for n in saved["nodes"]}
        first, last = {
            "proposed-ingestion": ("a7", "capturestore"),
            "proposed-batch-enrichment": ("dkind", "account"),
            "proposed-source-enrichment": ("parse", "data"),
        }[stem]
        detail_clipped = raster.render(saved, HERE / f"{stem}-detail.png",
            (0, nodes[first]["y"] - 50, right + 30, nodes[last]["y"] + 220), .8, spec["title"])
        receipt = dict(
            status="proposed report-model validation; no runtime execution or workflow acceptance",
            model=stem, source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            canvas_revision=result["revision"], canvas_nodes=len(saved["nodes"]), edges=len(saved["edges"]),
            numbered_steps=sum(bool(n.get("step")) for n in spec["nodes"]),
            extension_scenarios=len(scenarios), structural_reference_flags=[],
            card_overlaps=layout.overlaps(saved), edge_card_intersections=layout.routing().intersections(saved),
            overview_text_overflow=clipped, detail_text_overflow=detail_clipped,
            folded_terminal_behavior="identical labels, actors, outcomes, guards and extensions",
            presentation_proof=f"{stem}.presentation-proof.json", minimum_actor_pitch=600,
            call_outcomes=sorted({render.outcome(n) for n in spec["nodes"] if n["kind"] == "end"}),
            write="existing canvas service preview and revision/hash-checked commit; profile=None",
            curve_scope="deterministic reading preview with native attachment sides; not an Obsidian host screenshot")
        if clipped or detail_clipped:
            raise ValueError((stem, "preview text overflow", clipped, detail_clipped))
        receipt_path = HERE / f"{stem}.validation.json"
        if receipt_path.exists():
            previous = receipt_path.read_bytes()
            history = HERE / "authoring-history"
            history.mkdir(exist_ok=True)
            archive = history / f"{stem}.validation.{hashlib.sha256(previous).hexdigest()[:16]}.json"
            if not archive.exists():
                archive.write_bytes(previous)
        receipt_path.write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        receipts.append(receipt)
    (HERE / "validation.json").write_text(json.dumps(dict(completed_on="2026-11-23", models=receipts,
        new_library_model_calls=0, new_library_model_spend_usd=0), indent=2) + "\n", encoding="utf-8")
    print(json.dumps([dict(model=r["model"], nodes=r["canvas_nodes"], edges=r["edges"],
        steps=r["numbered_steps"], scenarios=r["extension_scenarios"],
        card_overlaps=r["card_overlaps"], edge_card_intersections=r["edge_card_intersections"],
        text_overflow=r["overview_text_overflow"] + r["detail_text_overflow"]) for r in receipts], indent=2))


if __name__ == "__main__":
    main()
