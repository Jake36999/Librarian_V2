import {chromium} from 'playwright-core';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
const base=process.argv[2];
const data=JSON.parse(readFileSync(path.join(base,'fixture-ready.json'),'utf8'));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(data.url);await page.waitForSelector('header nav');
 await page.getByRole('tab',{name:'Staging',exact:true}).click();
 await page.getByRole('button',{name:/^Folders/}).click();
 await page.getByRole('heading',{name:'Folder purposes'}).waitFor();
 await page.getByLabel('Which folders').selectOption('accepted');
 if(await page.getByText('Decided and applied by a person',{exact:true}).count()!==2)throw Error('Two accepted root decisions');
 await page.screenshot({path:path.join(base,'person-folders.png'),fullPage:true});
 await page.click('.lib-app nav button:has-text("Search")');
 await page.fill('.lib-search input[type=search]','Fixture Study');await page.keyboard.press('Enter');
 await page.locator('.lib-search .lib-tile .lib-wl').filter({hasText:'Fixture Study'}).first().click();
 const source=page.locator('[aria-label="Source navigator"]');
 await source.getByRole('heading',{name:'Source navigator',exact:true}).waitFor();
 if(await source.locator('details[open]').count())throw Error('Chapters must begin collapsed');
 await source.locator('details summary').first().click();
 if(!(await source.innerText()).includes('Not examined'))throw Error('Unread chapters labelled');
 await page.screenshot({path:path.join(base,'person-paper.png'),fullPage:true});
 const downloadPromise=page.waitForEvent('download');await source.getByRole('button',{name:'Open original',exact:true}).click();
 const download=await downloadPromise;await download.saveAs(path.join(base,'downloaded-original.pdf'));
 const hash=createHash('sha256').update(readFileSync(path.join(base,'downloaded-original.pdf'))).digest('hex');
 const original=createHash('sha256').update(readFileSync(path.join(data.third_party_root,'Study.pdf'))).digest('hex');
 if(hash!==original)throw Error('Downloaded original bytes differ');
 await page.fill('.lib-search input[type=search]','Ultravioletflux');await page.keyboard.press('Enter');
 await page.locator('.lib-search .lib-tile .lib-wl').filter({hasText:'workspace:'}).first().click();
 await page.locator('.lib-pane').getByText('Ultravioletflux procedure at the end.',{exact:false}).waitFor();
 if(!(await page.locator('.lib-pane').innerText()).includes('Read-only'))throw Error('Owner attachment is read-only');
 await page.screenshot({path:path.join(base,'person-own-document.png'),fullPage:true});
 if(errors.length)throw Error(JSON.stringify(errors));
 writeFileSync(path.join(base,'browser-result.json'),JSON.stringify({passed:7,model_calls:0,original_sha256:hash,page_errors:errors},null,2));
 console.log('7 real native Core/UI fixture checks passed; zero model calls');
} finally {await browser.close();}
