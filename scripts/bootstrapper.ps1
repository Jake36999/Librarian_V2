<#
.SYNOPSIS
    Installs a verified, hash-locked Librarian Windows release bundle.

.DESCRIPTION
    The bootstrapper intentionally refuses a development manifest, unhashed
    artifact, network dependency lookup, or unqualified release evidence.  It
    is suitable for a release bundle generated by build-release.ps1 and then
    signed/verified by the release process; it is not a replacement for the
    editable developer Setup.bat workflow.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ReleaseRoot,
    [string]$InstallRoot = (Join-Path $env:LOCALAPPDATA "Librarian"),
    [string]$Python = "python"
)

$ErrorActionPreference = "Stop"
$ReleaseRoot = [IO.Path]::GetFullPath($ReleaseRoot)
$InstallRoot = [IO.Path]::GetFullPath($InstallRoot)
$verifier = Join-Path $PSScriptRoot "verify-release.ps1"
if (-not (Test-Path -LiteralPath $verifier -PathType Leaf)) {
    throw "The bootstrapper requires its adjacent verify-release.ps1 verifier."
}
# This validates the detached CMS signature before using any path, package, or
# dependency record supplied by the bundle.
& $verifier -ReleaseRoot $ReleaseRoot
$manifestPath = Join-Path $ReleaseRoot "release-manifest.json"
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json

if (-not (Get-Command $Python -ErrorAction SilentlyContinue)) { throw "Python '$Python' was not found." }
$pythonMinor = (& $Python -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')").Trim()
if ($LASTEXITCODE -ne 0 -or $pythonMinor -notin @("3.11", "3.12", "3.13") -or
    @($manifest.supported_python | ForEach-Object { [string]$_ }) -notcontains $pythonMinor) {
    throw "Librarian stable releases require a supported Python 3.11, 3.12, or 3.13; found '$pythonMinor'."
}

function Resolve-BundlePath([string]$RelativePath, [string]$Name) {
    if ([string]::IsNullOrWhiteSpace($RelativePath)) { throw "$Name has no bundle-relative path." }
    $rootWithSeparator = $ReleaseRoot.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $fullPath = [IO.Path]::GetFullPath((Join-Path $ReleaseRoot $RelativePath))
    if (-not $fullPath.StartsWith($rootWithSeparator, [StringComparison]::OrdinalIgnoreCase)) {
        throw "$Name path escapes the release bundle."
    }
    return $fullPath
}

$wheel = Resolve-BundlePath $manifest.artifacts.core_wheel.path "Core wheel"
$hostCompanion = Resolve-BundlePath $manifest.artifacts.host_companion.path "Host companion"
$lock = Resolve-BundlePath $manifest.installer.requirements_lock "Requirements lock"
$wheelhouse = Resolve-BundlePath $manifest.installer.wheelhouse "Dependency wheelhouse"
$obsidianBundle = Resolve-BundlePath $manifest.artifacts.obsidian_bundle.path "Obsidian bundle"
$coworkBundle = Resolve-BundlePath $manifest.artifacts.cowork_bundle.path "Cowork bundle"

New-Item -ItemType Directory -Force -Path $InstallRoot | Out-Null
$venv = Join-Path $InstallRoot ".venv"
$venvPython = Join-Path $venv "Scripts\python.exe"
if (-not (Test-Path -LiteralPath $venvPython)) {
    & $Python -m venv $venv
    if ($LASTEXITCODE -ne 0) { throw "Could not create the Librarian environment." }
}
& $venvPython -m pip install --disable-pip-version-check --no-index --find-links $wheelhouse --require-hashes -r $lock
if ($LASTEXITCODE -ne 0) { throw "Hash-locked dependency installation failed." }
& $venvPython -m pip install --disable-pip-version-check --no-index --no-deps --upgrade --force-reinstall $wheel
if ($LASTEXITCODE -ne 0) { throw "Core wheel installation failed." }

Copy-Item -LiteralPath $manifestPath -Destination (Join-Path $InstallRoot "release-manifest.json") -Force
$signature = Resolve-BundlePath $manifest.signing.verification.signature_path "Manifest signature"
$leads = Resolve-BundlePath $manifest.release_leads.path "Release-lead manifest"
Copy-Item -LiteralPath $signature -Destination (Join-Path $InstallRoot "release-manifest.p7s") -Force
$installedLeads = Join-Path $InstallRoot "release-leads.json"
Copy-Item -LiteralPath $leads -Destination $installedLeads -Force
# Replace the development candidate that was packaged in the wheel with the
# same bundle-hashed stable record.  This keeps direct Core, Host, and
# adapter launches on the verified evidence path even when they do not start
# through Librarian.cmd.  The launcher below retains an explicit hash-bound
# override as an additional provenance check.
$packageLeads = (& $venvPython -c "from resource_librarian.hosts import RELEASE_LEADS_PATH; print(RELEASE_LEADS_PATH)").Trim()
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($packageLeads)) {
    throw "Could not locate Librarian's installed release-lead path."
}
$packageLeads = [IO.Path]::GetFullPath($packageLeads)
$venvWithSeparator = $venv.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
if (-not $packageLeads.StartsWith($venvWithSeparator, [StringComparison]::OrdinalIgnoreCase)) {
    throw "Installed release-lead path escapes the Librarian virtual environment."
}
Copy-Item -LiteralPath $leads -Destination $packageLeads -Force
& $venvPython -c "from resource_librarian.hosts import release_leads; record=release_leads(); assert record['integrity_valid'] and record['manifest_valid'], record['manifest_reason']"
if ($LASTEXITCODE -ne 0) { throw "Installed release-lead evidence did not pass the Core's fail-closed validation." }
Copy-Item -LiteralPath $hostCompanion -Destination (Join-Path $InstallRoot "LibrarianHost.ps1") -Force
# The release manifest hashes this script and the enclosing CMS signature
# verifies that manifest. Remove only a downloaded-file marker so standard
# Windows policy does not mistake this verified local copy for an arbitrary
# Internet script.
Unblock-File -LiteralPath (Join-Path $InstallRoot "LibrarianHost.ps1") -ErrorAction SilentlyContinue
$adapterRoot = Join-Path $InstallRoot "adapters"
New-Item -ItemType Directory -Force -Path $adapterRoot | Out-Null
Copy-Item -LiteralPath $obsidianBundle -Destination (Join-Path $adapterRoot "librarian-obsidian.zip") -Force
Copy-Item -LiteralPath $coworkBundle -Destination (Join-Path $adapterRoot "librarian-cowork.zip") -Force
$launcher = Join-Path $InstallRoot "Librarian.cmd"
$launcherText = "@echo off`r`nset `"LIBRARIAN_RELEASE_LEADS_PATH=$installedLeads`"`r`n" +
    "set `"LIBRARIAN_RELEASE_LEADS_SHA256=$($manifest.release_leads.sha256)`"`r`n" +
    "`"$venv\Scripts\librarian.exe`" %*`r`n"
[IO.File]::WriteAllText($launcher, $launcherText,
    [Text.UTF8Encoding]::new($false))
$hostLauncher = Join-Path $InstallRoot "LibrarianHost.cmd"
[IO.File]::WriteAllText($hostLauncher, "@echo off`r`npowershell.exe -NoLogo -NoProfile -File `"$InstallRoot\LibrarianHost.ps1`" -LibrarianExe `"$venv\Scripts\librarian.exe`" %*`r`n",
    [Text.UTF8Encoding]::new($false))
Write-Host "Installed Librarian $($manifest.version) at $InstallRoot" -ForegroundColor Green
Write-Host "Use: $launcher host start --vault D:\Research --open"
Write-Host "Or start the explicit tray companion: $hostLauncher"
