#!/usr/bin/env python
"""Write the E2' structure oracle for one task (tests/e2/test_<task>_structure.py).

The oracle is generated from the base: it freezes the module's public
top-level names, every class's public methods and the target's signature, and
requires the target to be at most the registry's max_target_lines long. It
fails at the base (the target is too long) and passes after a refactor that
splits the target into private helpers without changing the module's surface.

Usage: e2_structure.py E2-T06 [--registry PATH] [--repository DIR]
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path
from typing import Any


REPOSITORY = Path(__file__).resolve().parents[1]
REGISTRY = REPOSITORY / "docs" / "experiments" / "e2-prime-tasks.json"

TEMPLATE = '''"""E2' structure oracle for {task_id} (generated by scripts/e2_structure.py; do not edit).

{target} in {module} must be at most {max_lines} lines. The module's public
names, its classes' public methods and the target's signature must not change.
"""
from __future__ import annotations

import ast
from pathlib import Path

MODULE = Path(__file__).parents[2] / {module!r}
TARGET = {target!r}
MAX_LINES = {max_lines}
PUBLIC_NAMES = {public_names!r}
CLASS_PUBLIC_METHODS = {class_methods!r}
SIGNATURE = {signature!r}
# Every function's length at the base, so the body cannot simply move whole
# into one new helper or into an existing function.
BASE_FUNCTION_LINES = {function_lines!r}


def _tree():
    return ast.parse(MODULE.read_text(encoding="utf-8"))


def _target(tree):
    *owner, name = TARGET.split(".")
    scope = tree.body
    if owner:
        scope = next(n.body for n in tree.body if isinstance(n, ast.ClassDef) and n.name == owner[0])
    return next(n for n in scope
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == name)


def _public_names(tree):
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names.update(t.id for t in targets if isinstance(t, ast.Name))
    return sorted(n for n in names if not n.startswith("_"))


def _class_public_methods(tree):
    return {{node.name: sorted(n.name for n in node.body
                              if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                              and not n.name.startswith("_"))
            for node in tree.body if isinstance(node, ast.ClassDef)}}


def _function_lines(tree):
    lines = {{}}
    for node in tree.body:
        members = [(node.name + ".", n) for n in node.body] if isinstance(node, ast.ClassDef) \\
            else [("", node)]
        for prefix, item in members:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                lines[prefix + item.name] = item.end_lineno - item.lineno + 1
    return lines


def test_the_body_is_split_not_moved():
    for name, length in _function_lines(_tree()).items():
        allowed = max(BASE_FUNCTION_LINES.get(name, 0), MAX_LINES)
        if name == TARGET:
            allowed = MAX_LINES
        assert length <= allowed, f"{{name}} is {{length}} lines; at most {{allowed}} allowed"


def test_the_target_is_short():
    node = _target(_tree())
    length = node.end_lineno - node.lineno + 1
    assert length <= MAX_LINES, f"{{TARGET}} is {{length}} lines; at most {{MAX_LINES}} required"


def test_the_signature_is_unchanged():
    node = _target(_tree())
    returns = ast.unparse(node.returns) if node.returns else ""
    assert f"({{ast.unparse(node.args)}}) -> {{returns}}" == SIGNATURE


def test_no_public_name_is_added_or_removed():
    assert _public_names(_tree()) == PUBLIC_NAMES


def test_no_public_method_is_added_or_removed():
    assert _class_public_methods(_tree()) == CLASS_PUBLIC_METHODS
'''


def snapshot(module: Path, target: str) -> dict[str, Any]:
    tree = ast.parse(module.read_text(encoding="utf-8"))
    *owner, name = target.split(".")
    scope = tree.body
    if owner:
        scope = next(n.body for n in tree.body
                     if isinstance(n, ast.ClassDef) and n.name == owner[0])
    node = next(n for n in scope
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == name)
    names: set[str] = set()
    for item in tree.body:
        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(item.name)
        elif isinstance(item, (ast.Assign, ast.AnnAssign)):
            targets = item.targets if isinstance(item, ast.Assign) else [item.target]
            names.update(t.id for t in targets if isinstance(t, ast.Name))
    returns = ast.unparse(node.returns) if node.returns else ""
    function_lines: dict[str, int] = {}
    for item in tree.body:
        members = [(item.name + ".", n) for n in item.body] if isinstance(item, ast.ClassDef) \
            else [("", item)]
        for prefix, member in members:
            if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)):
                function_lines[prefix + member.name] = member.end_lineno - member.lineno + 1
    return {
        "function_lines": function_lines,
        "public_names": sorted(n for n in names if not n.startswith("_")),
        "class_methods": {c.name: sorted(n.name for n in c.body
                                         if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                                         and not n.name.startswith("_"))
                          for c in tree.body if isinstance(c, ast.ClassDef)},
        "signature": f"({ast.unparse(node.args)}) -> {returns}",
        "lines": node.end_lineno - node.lineno + 1,
    }


def render(task: dict[str, Any], repository: Path) -> str:
    snap = snapshot(repository / task["module"], task["target"])
    return TEMPLATE.format(task_id=task["id"], target=task["target"], module=task["module"],
                           max_lines=task["oracle"]["max_target_lines"],
                           public_names=snap["public_names"],
                           class_methods=snap["class_methods"], signature=snap["signature"],
                           function_lines=snap["function_lines"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("task_id")
    parser.add_argument("--registry", type=Path, default=REGISTRY)
    parser.add_argument("--repository", type=Path, default=REPOSITORY)
    args = parser.parse_args(argv)
    tasks = {t["id"]: t for t in json.loads(args.registry.read_text(encoding="utf-8"))["tasks"]}
    if args.task_id not in tasks:
        raise SystemExit(f"unknown task {args.task_id}; known: {sorted(tasks)}")
    task = tasks[args.task_id]
    short = args.task_id.removeprefix("E2-")
    out = args.repository / "tests" / "e2" / f"test_{short}_structure.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(task, args.repository), encoding="utf-8", newline="\n")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
